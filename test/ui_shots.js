// screenshots de modais e lobby
const { chromium } = require('playwright'); const http = require('http'), fs = require('fs'), path = require('path');
const SC = '/tmp/claude-0/-home-claude/af606cd0-1bcb-5f4b-9907-dd7d470f58f8/scratchpad/';
const html = fs.readFileSync(path.resolve(__dirname, '../dist/index.html'));
const srv = http.createServer((q, r) => { r.writeHead(200, { 'content-type': 'text/html; charset=utf-8' }); r.end(html); });
(async () => {
  const W = +process.argv[2] || 1280, H = +process.argv[3] || 720, tag = process.argv[4] || 'ui';
  await new Promise(r => srv.listen(0, '127.0.0.1', r)); const port = srv.address().port;
  const browser = await chromium.launch({ args: ['--use-angle=swiftshader', '--use-gl=angle', '--enable-unsafe-swiftshader', '--ignore-gpu-blocklist', '--enable-webgl', '--no-sandbox'] });
  const page = await browser.newPage({ viewport: { width: W, height: H } }); const logs = [];
  page.on('console', m => { if (m.type() === 'error' && !/TUNNEL|Failed to load resource/.test(m.text())) logs.push('err: ' + m.text().slice(0, 200)); }); page.on('pageerror', e => logs.push('PAGEERROR: ' + e.message));
  await page.addInitScript(`try{localStorage.setItem('bombaki2.settings', JSON.stringify({quality:'baixo', renderScale:0.4}))}catch(e){}`);
  await page.goto(`http://127.0.0.1:${port}/?net=local&test=1`); await page.waitForFunction('window.G && G.scene === "menu"', null, { timeout: 180000 });
  const shot = async n => { await page.waitForTimeout(900); await page.screenshot({ path: SC + tag + '_' + n + '.png', timeout: 120000 }); };
  await shot('menu');
  const click = async sel => { await page.click(sel); };
  await click('#bPlay'); await shot('play');
  await page.evaluate('UI.close()'); await page.waitForTimeout(300);
  await click('#bCreate'); await shot('create');
  await page.evaluate('UI.close()'); await page.waitForTimeout(300);
  await click('#bJoin'); await shot('join');
  await page.evaluate('UI.close()'); await page.waitForTimeout(300);
  await click('#bSet'); await shot('settings');
  await page.evaluate('UI.close()'); await page.waitForTimeout(300);
  await click('#bStats'); await shot('stats');
  await page.evaluate('UI.close()'); await page.waitForTimeout(300);
  await click('#bFriends'); await shot('friends');
  await page.evaluate('UI.close()'); await page.waitForTimeout(300);
  await click('#pAv'); await shot('avatar');
  await page.evaluate('UI.close()'); await page.waitForTimeout(300);
  await page.evaluate(`Game.hostRoom({ mode: 'tatico', fill: true, rounds: 3 })`); await shot('lobby');
  console.log(logs.join('\n') || 'ok'); await browser.close(); srv.close();
})().catch(e => { console.error('ERRO', e); process.exit(2); });
